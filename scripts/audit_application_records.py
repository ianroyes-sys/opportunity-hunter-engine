#!/usr/bin/env python3
"""Read-only consistency check for application history and submission evidence."""
from __future__ import annotations

import argparse
import csv
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def key(value: str) -> str:
    value = value.lower().replace("&", " and ")
    value = re.sub(r"\b(inc|llc|ltd|corp|corporation|company|co)\b", " ", value)
    return re.sub(r"[^a-z0-9]+", "-", value).strip("-")


def markdown_rows(path: Path) -> list[list[str]]:
    rows = []
    try:
        for line in path.read_text(errors="replace").splitlines():
            if not line.startswith("|") or "---" in line:
                continue
            cells = [c.strip() for c in line.strip("|").split("|")]
            if len(cells) > 2 and not any(c.lower() in {"date", "timestamp"} for c in cells):
                rows.append(cells)
    except OSError:
        pass
    return rows


def csv_rows(path: Path) -> list[dict[str, str]]:
    try:
        with path.open(newline="", errors="replace") as fh:
            return list(csv.DictReader(fh))
    except OSError:
        return []


parser = argparse.ArgumentParser()
parser.add_argument("--write", action="store_true", help="write pipeline/RECONCILIATION.md")
args = parser.parse_args()

sources: dict[str, list[str]] = defaultdict(list)
for row in markdown_rows(ROOT / "pipeline" / "SUBMISSIONS.md"):
    # Date | Opportunity | Type | Channel | Confirmation | Materials
    if len(row) >= 2:
        sources[key(re.sub(r"\*|\[.*?\]", "", row[1]).replace("— SUBMITTED", ""))].append("pipeline/SUBMISSIONS.md")
for row in markdown_rows(ROOT / "career-ledger" / "EXTERNAL_ACTIONS.md"):
    # Timestamp | Action | Target | Outcome | Materials. Discovery rows are not applications.
    if len(row) >= 3 and "application submitted" in row[1].lower():
        sources[key(re.sub(r"\*|\[.*?\]", "", row[2]))].append("career-ledger/EXTERNAL_ACTIONS.md")
for file in ("APPLICATION_HISTORY.csv", "JOB_TRACKER.csv"):
    for row in csv_rows(ROOT / "career-ledger" / file):
        title = next((v for k, v in row.items() if k and any(x in k.lower() for x in ("company", "role", "job", "title", "opportunity")) and v), "")
        if title:
            sources[key(title)].append(f"career-ledger/{file}")

dupes = {k: v for k, v in sources.items() if len(set(v)) > 1}
records = {key(p.stem) for p in (ROOT / "pipeline" / "opportunities").glob("*.md")}
def has_record(entry: str) -> bool:
    words = {w for w in entry.split("-") if len(w) > 2}
    return any(len(words & set(record.split("-"))) >= min(2, len(words)) for record in records)
missing = sorted(k for k, refs in sources.items() if any("SUBMISSIONS" in ref for ref in refs) and not has_record(k))

lines = [
    "# Application Record Reconciliation", "",
    "Generated by scripts/audit_application_records.py; it never changes history.", "",
    f"- Distinct normalized entries: **{len(sources)}**",
    f"- Entries in multiple ledgers: **{len(dupes)}**",
    f"- Submission entries without a same-key opportunity record: **{len(missing)}**", "",
    "## Review queue",
]
lines.extend(f"- {name}: {', '.join(sorted(set(refs)))}" for name, refs in sorted(dupes.items()))
if not dupes:
    lines.append("- No cross-ledger matches found by conservative title normalization.")
if missing:
    lines.extend(["", "## Missing opportunity-record candidates"])
    lines.extend(f"- {name}" for name in missing[:100])
report = "\n".join(lines) + "\n"
if args.write:
    (ROOT / "pipeline" / "RECONCILIATION.md").write_text(report)
print(report, end="")
